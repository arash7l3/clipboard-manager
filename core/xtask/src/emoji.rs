//! `cargo xtask emoji <emoji-test.txt>`: regenerates `core/src/emoji/emoji.txt`,
//! the emoji list built into the core, from Unicode's `emoji-test.txt`.
//!
//! Get the input from `https://unicode.org/Public/emoji/<version>/emoji-test.txt`.
//! Only emoji up to [`MAX_VERSION`] are kept, so that every one in the list is
//! drawn by the oldest supported systems (macOS 14, Windows 11). Raise it when
//! the minimum OS draws newer emoji.

use std::fmt::Write as _;

use anyhow::{bail, Context, Result};
use camino::Utf8Path;

/// Newest emoji version kept: the one macOS 14 and Windows 11 both draw.
const MAX_VERSION: (u32, u32) = (15, 0);

/// Unicode groups in picker order, with the key written to the list. Smileys
/// and people share one group, as in the macOS picker; Activities comes before
/// Travel, also as there. Unicode's "Component" group (skin-tone and hair
/// swatches) is left out.
const GROUPS: [(&str, &[&str]); 8] = [
    ("smileys-people", &["Smileys & Emotion", "People & Body"]),
    ("animals-nature", &["Animals & Nature"]),
    ("food-drink", &["Food & Drink"]),
    ("activities", &["Activities"]),
    ("travel-places", &["Travel & Places"]),
    ("objects", &["Objects"]),
    ("symbols", &["Symbols"]),
    ("flags", &["Flags"]),
];

const SKIPPED_GROUPS: [&str; 1] = ["Component"];

/// Writes the list for `input` to `core/src/emoji/emoji.txt`.
pub(crate) fn generate(input: &Utf8Path) -> Result<()> {
    let text = std::fs::read_to_string(input).with_context(|| format!("reading {input}"))?;
    let list = convert(&text)?;
    let output = crate::core_dir().join("src/emoji/emoji.txt");
    std::fs::write(&output, list).with_context(|| format!("writing {output}"))?;
    println!("wrote {output}");
    Ok(())
}

/// The list file for an `emoji-test.txt`.
fn convert(text: &str) -> Result<String> {
    let mut groups: Vec<Vec<String>> = vec![Vec::new(); GROUPS.len()];
    let mut current: Option<usize> = None;
    let mut source_version = None;
    let mut copyright = None;
    for line in text.lines() {
        if let Some(version) = line.strip_prefix("# Version: ") {
            source_version = Some(version.trim().to_owned());
        }
        if line.starts_with("# \u{A9}") && copyright.is_none() {
            copyright = Some(line.trim_start_matches("# ").trim().to_owned());
        }
        if let Some(name) = line.strip_prefix("# group: ") {
            let name = name.trim();
            current = GROUPS.iter().position(|(_, names)| names.contains(&name));
            if current.is_none() && !SKIPPED_GROUPS.contains(&name) {
                bail!("unknown emoji group {name:?}: add it to GROUPS or SKIPPED_GROUPS");
            }
            continue;
        }
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let Some(group) = current else { continue };
        if let Some(entry) = entry(line)? {
            groups[group].push(entry);
        }
    }

    let source = source_version.as_deref().unwrap_or("(unknown version)");
    let copyright = copyright.as_deref().unwrap_or("\u{A9} Unicode, Inc.");
    let (major, minor) = MAX_VERSION;
    let mut out = String::new();
    writeln!(
        out,
        "# Emoji built into Clipo, in picker order. Generated by `cargo xtask emoji`\n\
         # from Unicode emoji-test.txt {source}: fully-qualified emoji up to Emoji {major}.{minor},\n\
         # without skin-tone variants. Do not edit by hand.\n\
         # Unicode data {copyright}, under the Unicode License v3:\n\
         # https://www.unicode.org/license.txt\n\
         # Each group starts with `[key]`; each emoji line is `<emoji> <name>`."
    )?;
    for ((key, _), entries) in GROUPS.iter().zip(&groups) {
        if entries.is_empty() {
            bail!("no emoji found for group {key}");
        }
        writeln!(out, "[{key}]")?;
        for entry in entries {
            writeln!(out, "{entry}")?;
        }
    }
    Ok(out)
}

/// `<emoji> <name>` for a data line, or `None` for a line that is left out.
///
/// A data line looks like
/// `1F600 ; fully-qualified # 😀 E1.0 grinning face`.
fn entry(line: &str) -> Result<Option<String>> {
    let (fields, comment) = line
        .split_once('#')
        .with_context(|| format!("no comment in line {line:?}"))?;
    let (code_points, status) = fields
        .split_once(';')
        .with_context(|| format!("no status in line {line:?}"))?;
    if status.trim() != "fully-qualified" {
        return Ok(None);
    }
    let mut chars = String::new();
    for hex in code_points.split_whitespace() {
        let value =
            u32::from_str_radix(hex, 16).with_context(|| format!("bad code point {hex}"))?;
        let c = char::from_u32(value).with_context(|| format!("bad code point {hex}"))?;
        // Skin-tone modifiers: v1 lists the default yellow form only.
        if ('\u{1F3FB}'..='\u{1F3FF}').contains(&c) {
            return Ok(None);
        }
        chars.push(c);
    }
    let mut words = comment.trim().splitn(3, ' ');
    let (Some(shown), Some(version), Some(name)) = (words.next(), words.next(), words.next())
    else {
        bail!("bad comment in line {line:?}");
    };
    if shown != chars {
        bail!("code points and emoji differ in line {line:?}");
    }
    if version_of(version)? > MAX_VERSION {
        return Ok(None);
    }
    Ok(Some(format!("{chars} {}", name.trim())))
}

/// `(major, minor)` for `E15.0`.
fn version_of(text: &str) -> Result<(u32, u32)> {
    let parsed = text
        .strip_prefix('E')
        .and_then(|v| v.split_once('.'))
        .and_then(|(major, minor)| Some((major.parse().ok()?, minor.parse().ok()?)));
    parsed.with_context(|| format!("bad emoji version {text:?}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "\
# Version: 99.0
# \u{A9} 2099 Unicode\u{AE}, Inc.
# group: Smileys & Emotion
# subgroup: face-smiling
1F600 ; fully-qualified # \u{1F600} E1.0 grinning face
263A FE0F ; fully-qualified # \u{263A}\u{FE0F} E0.6 smiling face
263A ; unqualified # \u{263A} E0.6 smiling face
1FAE8 ; fully-qualified # \u{1FAE8} E15.0 shaking face
1F642 200D 2194 FE0F ; fully-qualified # \u{1F642}\u{200D}\u{2194}\u{FE0F} E15.1 head shaking horizontally
# group: People & Body
1F44D ; fully-qualified # \u{1F44D} E0.6 thumbs up
1F44D 1F3FB ; fully-qualified # \u{1F44D}\u{1F3FB} E1.0 thumbs up: light skin tone
# group: Component
1F3FB ; component # \u{1F3FB} E1.0 light skin tone
# group: Animals & Nature
1F436 ; fully-qualified # \u{1F436} E0.6 dog face
# group: Food & Drink
1F34E ; fully-qualified # \u{1F34E} E0.6 red apple
# group: Activities
26BD ; fully-qualified # \u{26BD} E0.6 soccer ball
# group: Travel & Places
1F697 ; fully-qualified # \u{1F697} E0.6 automobile
# group: Objects
1F4A1 ; fully-qualified # \u{1F4A1} E0.6 light bulb
# group: Symbols
2764 FE0F ; fully-qualified # \u{2764}\u{FE0F} E0.6 red heart
# group: Flags
1F1F2 1F1F3 ; fully-qualified # \u{1F1F2}\u{1F1F3} E2.0 flag: Mongolia
";

    #[test]
    fn keeps_fully_qualified_emoji_without_skin_tones_up_to_the_max_version() {
        let out = convert(SAMPLE).unwrap();
        let body: Vec<&str> = out.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            body,
            [
                "[smileys-people]",
                "\u{1F600} grinning face",
                "\u{263A}\u{FE0F} smiling face",
                "\u{1FAE8} shaking face",
                "\u{1F44D} thumbs up",
                "[animals-nature]",
                "\u{1F436} dog face",
                "[food-drink]",
                "\u{1F34E} red apple",
                // Activities before Travel, unlike Unicode's order.
                "[activities]",
                "\u{26BD} soccer ball",
                "[travel-places]",
                "\u{1F697} automobile",
                "[objects]",
                "\u{1F4A1} light bulb",
                "[symbols]",
                "\u{2764}\u{FE0F} red heart",
                "[flags]",
                "\u{1F1F2}\u{1F1F3} flag: Mongolia",
            ]
        );
        assert!(out.contains("emoji-test.txt 99.0"));
        assert!(
            out.contains("Unicode data \u{A9} 2099 Unicode\u{AE}, Inc., under the Unicode License")
        );
    }

    #[test]
    fn rejects_an_unknown_group() {
        let err = convert("# group: Something New\n").unwrap_err();
        assert!(err.to_string().contains("Something New"));
    }
}
