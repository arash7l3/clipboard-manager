import AppKit
@testable import Clipo
import ClipoCore
import Testing

/// A private, uniquely named pasteboard, so tests never touch the user's clipboard.
@MainActor
final class TestPasteboard {
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("io.github.arash7l3.Clipo.tests.\(UUID().uuidString)"))

    func set(_ text: String, extra: [NSPasteboard.PasteboardType: Data] = [:]) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        for (type, data) in extra {
            pasteboard.setData(data, forType: type)
        }
    }

    /// A new five-byte file in the temporary folder; the caller deletes it.
    static func temporaryFile() throws -> URL {
        let file = FileManager.default.temporaryDirectory
            .appendingPathComponent("clipo-test-\(UUID().uuidString).txt")
        try Data("12345".utf8).write(to: file)
        return file
    }

    /// The `file:///.file/id=…` form of `url`, as Finder puts it on the pasteboard.
    static func referenceString(for url: URL) throws -> String {
        // The Objective-C method: Swift's URL would turn the reference back into a path.
        let result = (url as NSURL).perform(#selector(NSURL.fileReferenceURL))
        let reference = try #require(result?.takeUnretainedValue() as? NSURL)
        return try #require(reference.absoluteString)
    }

    /// A tiny PNG of `width` by `height` pixels.
    static func png(width: Int, height: Int) throws -> Data {
        let bitmap = try #require(NSBitmapImageRep(
            bitmapDataPlanes: nil,
            pixelsWide: width,
            pixelsHigh: height,
            bitsPerSample: 8,
            samplesPerPixel: 4,
            hasAlpha: true,
            isPlanar: false,
            colorSpaceName: .deviceRGB,
            bytesPerRow: 0,
            bitsPerPixel: 0
        ))
        return try #require(bitmap.representation(using: .png, properties: [:]))
    }
}

@MainActor
struct PasteboardReaderTests {
    private let board = TestPasteboard()
    private let now = Date()

    private func capture(_ content: PasteboardContent?, maxItemBytes: Int = 1_000_000) -> Capture? {
        content.flatMap {
            PasteboardReader.capture(from: $0, sourceApp: nil, at: now, maxItemBytes: maxItemBytes)
        }
    }

    @Test func readsTextWithItsRichForm() throws {
        board.set("سلام", extra: [.rtf: Data(#"{\rtf1 hi}"#.utf8)])

        guard case let .text(plain, rtf, html) = PasteboardReader.content(of: board.pasteboard) else {
            Issue.record("text is read")
            return
        }
        #expect(plain == "سلام")
        #expect(rtf != nil)
        #expect(html == nil)

        let result = try #require(capture(PasteboardReader.content(of: board.pasteboard)))
        guard case let .text(text) = result.content else {
            Issue.record("a text capture")
            return
        }
        #expect(text.plain == "سلام")
        #expect(text.rich?.format == .rtf)
        #expect(result.capturedAt == now)
        #expect(!result.concealed)
    }

    @Test func concealedDataIsNotRead() {
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        board.set("hunter2", extra: [concealed: Data("1".utf8)])
        #expect(PasteboardReader.isConcealed(board.pasteboard))
        #expect(PasteboardReader.content(of: board.pasteboard) == nil)
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ])
    func everyMarkerCountsAsConcealed(marker: String) {
        board.set("secret", extra: [NSPasteboard.PasteboardType(marker): Data("1".utf8)])
        #expect(PasteboardReader.content(of: board.pasteboard) == nil)
    }

    @Test func plainTextIsNotConcealed() {
        board.set("hello")
        #expect(!PasteboardReader.isConcealed(board.pasteboard))
    }

    @Test func emptyPasteboardHasNoContent() {
        board.pasteboard.clearContents()
        #expect(PasteboardReader.content(of: board.pasteboard) == nil)
    }

    @Test func whitespaceOnlyTextIsNotKept() {
        board.set(" \n\t ")
        #expect(capture(PasteboardReader.content(of: board.pasteboard)) == nil)
    }

    @Test func filesComeBeforeTheirNameAsText() throws {
        let file = FileManager.default.temporaryDirectory
            .appendingPathComponent("clipo-test-\(UUID().uuidString).txt")
        try Data("12345".utf8).write(to: file)
        defer { try? FileManager.default.removeItem(at: file) }

        board.pasteboard.clearContents()
        #expect(board.pasteboard.writeObjects([file as NSURL]))
        board.pasteboard.setString(file.lastPathComponent, forType: .string)

        let result = try #require(capture(PasteboardReader.content(of: board.pasteboard)))
        guard case let .files(files) = result.content else {
            Issue.record("files win over text")
            return
        }
        #expect(files.count == 1)
        #expect(files.first?.path.hasSuffix(file.lastPathComponent) == true)
        #expect(files.first?.sizeBytes == 5)
    }

    @Test func finderFileReferencesAreKeptAsPaths() throws {
        let file = try TestPasteboard.temporaryFile()
        defer { try? FileManager.default.removeItem(at: file) }
        let item = NSPasteboardItem()
        item.setString(try TestPasteboard.referenceString(for: file), forType: .fileURL)
        board.pasteboard.clearContents()
        #expect(board.pasteboard.writeObjects([item]))

        guard case let .files(urls)? = PasteboardReader.content(of: board.pasteboard) else {
            Issue.record("files are read")
            return
        }
        let path = try #require(urls.first?.path)
        #expect(urls.count == 1)
        #expect(!path.hasPrefix(PasteboardReader.referencePrefix))
        #expect(FileManager.default.fileExists(atPath: path))
        #expect(urls.first?.lastPathComponent == file.lastPathComponent)
    }

    @Test func tooManyFilesAreNotKept() {
        let urls = (0...PasteboardReader.maxFiles).map { URL(fileURLWithPath: "/tmp/clipo-\($0)") }
        #expect(capture(.files(urls)) == nil)
    }

    @Test func imageGetsSizeAndThumbnail() throws {
        let png = try TestPasteboard.png(width: 600, height: 300)
        board.pasteboard.clearContents()
        board.pasteboard.setData(png, forType: .png)

        let result = try #require(capture(PasteboardReader.content(of: board.pasteboard)))
        guard case let .image(image) = result.content else {
            Issue.record("an image capture")
            return
        }
        #expect(image.format == .png)
        #expect(image.width == 600)
        #expect(image.height == 300)
        #expect(image.data == png)

        let thumbnail = try #require(image.thumbnail.flatMap { NSBitmapImageRep(data: $0) })
        #expect(thumbnail.pixelsWide == PasteboardReader.thumbnailPixels)
        #expect(thumbnail.pixelsHigh == PasteboardReader.thumbnailPixels / 2)
    }

    @Test func textIsPreferredOverAnImageOfIt() throws {
        let png = try TestPasteboard.png(width: 4, height: 4)
        board.set("cell", extra: [.png: png])
        guard case .text = PasteboardReader.content(of: board.pasteboard) else {
            Issue.record("text wins over an image")
            return
        }
    }

    @Test func oversizedImageIsNotKept() throws {
        let png = try TestPasteboard.png(width: 64, height: 64)
        #expect(capture(.image(png, .png), maxItemBytes: png.count - 1) == nil)
        #expect(capture(.image(png, .png), maxItemBytes: png.count) != nil)
    }

    @Test func undecodableImageIsNotKept() {
        #expect(capture(.image(Data("not an image".utf8), .png)) == nil)
    }

    @Test func oversizedRichFormIsDroppedButTextStays() throws {
        let rtf = Data(String(repeating: "a", count: 100).utf8)
        let result = try #require(capture(.text("hi", rtf: rtf, html: nil), maxItemBytes: 50))
        guard case let .text(text) = result.content else {
            Issue.record("a text capture")
            return
        }
        #expect(text.plain == "hi")
        #expect(text.rich == nil)
    }
}
