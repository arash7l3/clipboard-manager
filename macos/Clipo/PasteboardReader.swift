import AppKit
import ClipoCore
import ImageIO
import UniformTypeIdentifiers

/// What one clipboard change holds, as raw data copied out of the pasteboard.
///
/// Reading the pasteboard has to happen on the main thread; turning the data
/// into a ``Capture`` (decoding images, asking the file system for sizes) does
/// not, so the two steps are separate. A change holds one kind of content,
/// picked in the order files, text, image: Finder puts a file's name on the
/// pasteboard as text too, and a spreadsheet range comes with a picture.
enum PasteboardContent: Sendable, Equatable {
    case files([URL])
    case text(String, rtf: Data?, html: Data?)
    case image(Data, ImageFormat)
}

/// Reads the pasteboard and builds captures for the core.
enum PasteboardReader {
    /// Types that apps put on the pasteboard to say "do not keep this", from
    /// the nspasteboard.org convention and password managers. Data with any of
    /// them is not even read.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType"
    ]

    /// More files than this in one copy are not kept; the list would be huge
    /// and each file costs a file-system call.
    static let maxFiles = 1000

    /// Images with more pixels than this are not kept; decoding them to make a
    /// thumbnail would take too much memory.
    static let maxPixels = 100_000_000

    /// Longest side of the thumbnail stored with an image, in pixels.
    static let thumbnailPixels = 256

    /// Whether the data on `pasteboard` is marked as one to forget.
    @MainActor
    static func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let types = pasteboard.types ?? []
        return types.contains { concealedTypes.contains($0.rawValue) }
    }

    /// The content of the pasteboard, or `nil` if it is concealed, empty or
    /// holds nothing Clipo keeps. Concealed data is never read.
    @MainActor
    static func content(of pasteboard: NSPasteboard) -> PasteboardContent? {
        guard !isConcealed(pasteboard) else { return nil }

        let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        if !urls.isEmpty {
            return .files(urls)
        }

        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return .text(text, rtf: pasteboard.data(forType: .rtf), html: pasteboard.data(forType: .html))
        }

        if let png = pasteboard.data(forType: .png) {
            return .image(png, .png)
        }
        if let tiff = pasteboard.data(forType: .tiff) {
            return .image(tiff, .tiff)
        }
        return nil
    }

    /// The capture for `content`, or `nil` if it is not worth keeping or is
    /// larger than `maxItemBytes` (the core would skip those anyway; this
    /// avoids decoding them first).
    static func capture(
        from content: PasteboardContent,
        sourceApp: SourceApp?,
        at date: Date,
        maxItemBytes: Int
    ) -> Capture? {
        let itemContent: ItemContent?
        switch content {
        case let .files(urls):
            itemContent = filesContent(urls)
        case let .text(text, rtf, html):
            itemContent = textContent(text, rtf: rtf, html: html, maxBytes: maxItemBytes)
        case let .image(data, format):
            itemContent = imageContent(data, format: format, maxBytes: maxItemBytes)
        }
        return itemContent.map { Capture(content: $0, sourceApp: sourceApp, capturedAt: date) }
    }

    private static func filesContent(_ urls: [URL]) -> ItemContent? {
        guard urls.count <= maxFiles else { return nil }
        let files = urls.map { url in
            let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize
            return FileRef(path: url.path, sizeBytes: size.flatMap { UInt64(exactly: $0) })
        }
        return .files(files: files)
    }

    private static func textContent(_ text: String, rtf: Data?, html: Data?, maxBytes: Int) -> ItemContent? {
        // Whitespace alone is not worth a history entry.
        guard !text.allSatisfy(\.isWhitespace) else { return nil }
        let rich: RichText?
        if let rtf, rtf.count <= maxBytes, let markup = decodeMarkup(rtf) {
            rich = RichText(format: .rtf, data: markup)
        } else if let html, html.count <= maxBytes, let markup = decodeMarkup(html) {
            rich = RichText(format: .html, data: markup)
        } else {
            rich = nil
        }
        return .text(text: TextContent(plain: text, rich: rich))
    }

    /// RTF is ASCII with escapes; HTML on the pasteboard is UTF-8. Latin-1
    /// accepts any bytes, so an odd encoding still gives a string.
    private static func decodeMarkup(_ data: Data) -> String? {
        String(data: data, encoding: .utf8) ?? String(data: data, encoding: .isoLatin1)
    }

    private static func imageContent(_ data: Data, format: ImageFormat, maxBytes: Int) -> ItemContent? {
        guard data.count <= maxBytes,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = pixels(properties[kCGImagePropertyPixelWidth]),
              let height = pixels(properties[kCGImagePropertyPixelHeight]),
              UInt64(width) * UInt64(height) <= UInt64(maxPixels)
        else { return nil }
        let image = ImageContent(
            format: format,
            width: width,
            height: height,
            data: data,
            thumbnail: thumbnail(of: source)
        )
        return .image(image: image)
    }

    /// A positive pixel count from an ImageIO property.
    private static func pixels(_ value: Any?) -> UInt32? {
        guard let number = value as? NSNumber, let count = UInt32(exactly: number.intValue), count > 0 else {
            return nil
        }
        return count
    }

    /// A PNG of the image no longer than ``thumbnailPixels`` on a side.
    private static func thumbnail(of source: CGImageSource) -> Data? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailPixels
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return nil
        }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            output,
            UTType.png.identifier as CFString,
            1,
            nil
        ) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }
}
